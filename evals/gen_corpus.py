"""Reproduce the small synthetic release fixture without network or real data."""

from __future__ import annotations

import argparse
from pathlib import Path

from megamind.fsops import atomic_write_path


FILES = {
    "README.md": "Synthetic release benchmark fixture. All content is invented and safe to publish.\n",
    "ProductWiki/pricing.md": "# Pricing\nThe synthetic product has a starter plan and a team plan.\n",
    "ProductWiki/release.md": "# Release\nSynthetic releases use a staged rollout and a published release note.\n",
    "DigestWiki/DIGEST.md": "# Research digest\nSynthetic research study summaries are safe to share as a digest.\n",
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("target", type=Path)
    parser.add_argument("--replace", action="store_true", help="replace only files generated by this script")
    args = parser.parse_args()
    target = args.target.resolve()
    if target.exists() and not args.replace:
        raise SystemExit("refusing to replace an existing fixture; pass --replace deliberately")
    for relative, content in FILES.items():
        atomic_write_path(target / relative, content, durable=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
